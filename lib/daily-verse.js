const DAY_MS = 86400000;
function dayNumber(now) {
  const ymd = now.toLocaleDateString('en-CA', { timeZone: 'Asia/Taipei' });
  return Math.floor(Date.parse(`${ymd}T00:00:00Z`) / DAY_MS);
}

function verseOf(now = new Date()) {
  return VERSES[dayNumber(now) % VERSES.length];
}

function handleVerse(now = new Date()) {
  const [ref, text] = verseOf(now);
  return `📖 今天的一句\n\n「${text}」\n—— ${ref}（和合本）`;
}

function isVerseCommand(t) {
  return /^(?:每日一句|今日一句|每日經文|今日經文|今天的一句)$/.test(String(t || '').trim());
}

module.exports = { VERSES, verseOf, handleVerse, isVerseCommand };
